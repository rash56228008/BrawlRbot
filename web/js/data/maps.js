// Карты: сетки 26×16 (клетка 40px => мир 1040×640... используем 30×18 = 1200×720)
// Легенда: '#' стена, '.' куст, ' ' пусто, 'B' ящик, 'W' вода (непроходима для пуль? нет — вода проходима для пуль, нет ходьбы),
// 'S' спавн (A/B в зависимости от команды — см. ниже), 's' спавн-соло, 'G' точка гема, 'F' мяч/флаг, 'Z' зона, 'X' сейф
// Карты пишутся строками одинаковой длины 30.

export const TILE = 40;
export const MAP_W = 30;
export const MAP_H = 18;

function pad(rows) {
  return rows.map((r) => {
    // дополняем стенами, чтобы границы всегда были закрыты
    const padded = r.padEnd(MAP_W, '#');
    return padded.slice(0, MAP_W);
  });
}

// Шаблоны для генерации зеркальных карт (левая половина 15 колонок отражается)
function mirror(left) {
  return left.map((row) => {
    const full = row.padEnd(15, ' ');
    return full + [...full].reverse().join('');
  });
}

