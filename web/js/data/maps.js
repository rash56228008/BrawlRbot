// Карта для дружеских боёв: любая по режиму
export function mapsForMode(modeId) {
  const list = MAPS.filter((m) => m.id === modeId);
  return list.length ? list : MAPS.filter((m) => m.mode === modeId);
}

// Валидация карты (используется и редактором)
export function validateMap(rows) {
  if (!Array.isArray(rows) || rows.length === 0) return { ok: false, error: 'Пустая карта' };
  const w = rows[0].length;
  if (w !== MAP_W) return { ok: false, error: `Ширина ${w}, нужно ${MAP_W}` };
  for (const r of rows) {
    if (r.length !== w) return { ok: false, error: 'Строки разной длины' };
    for (const ch of r) {
      if (!' #.BsGSF XZ'.includes(ch)) return { ok: false, error: 'Неизвестный символ: ' + ch };

    }
  }
  // Границы: боковые столбцы всегда стены; верх/низ допускают центральный проход ≤ 6 клеток («ворота»)
  for (const r of rows) {
    if (r[0] !== '#' || r[r.length - 1] !== '#') return { ok: false, error: 'Боковая граница без стены' };
  }
  for (const row of [rows[0], rows[rows.length - 1]]) {
    const open = [...row].filter((c) => c !== '#');
    if (open.length > 6) return { ok: false, error: 'Верх/низ без стены (открыто > 6 клеток)' };
  }
  return { ok: true };
}
